// Bundles public/ into src/static.js so the worker serves the pages itself (no separate asset upload).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const types = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', png: 'image/png', js: 'text/javascript; charset=utf-8' };
const out = {};
for (const f of readdirSync('public')) {
  const ext = f.split('.').pop();
  out['/' + f] = { type: types[ext] || 'application/octet-stream', b64: readFileSync('public/' + f).toString('base64') };
}
writeFileSync('src/static.js', '// Generated by build-static.mjs from public/. Do not edit.\nexport default ' + JSON.stringify(out) + ';\n');
console.log('bundled', Object.keys(out).join(', '));
